#!/usr/bin/env python3
"""Build first-install Gutenberg content from the approved legacy templates.

Development-only generator; WordPress never executes Python. Existing customer
content is never regenerated by this script or replaced by the PHP migration.
"""
from html.parser import HTMLParser
from html import escape
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1] / 'themes/noav-live'
MEDIA = {}
VOID = {'img','br','hr','input','meta','link','source','wbr','area','base','embed','param','track','col'}
class Node:
    def __init__(self, tag='', attrs=None):
        self.tag, self.attrs, self.children = tag, dict(attrs or []), []
    def walk(self):
        yield self
        for child in self.children:
            if isinstance(child, Node): yield from child.walk()
    def find(self, predicate): return next((n for n in self.walk() if predicate(n)), None)
    def all(self, tag): return [n for n in self.walk() if n.tag == tag]
    def text(self): return ''.join(c.text() if isinstance(c, Node) else c for c in self.children)
class Tree(HTMLParser):
    def __init__(self, source):
        super().__init__(convert_charrefs=True)
        self.root=Node(); self.stack=[self.root]; self.feed(source)
    def handle_starttag(self, tag, attrs):
        node=Node(tag,attrs); self.stack[-1].children.append(node)
        if tag not in VOID: self.stack.append(node)
    def handle_startendtag(self,tag,attrs): self.handle_starttag(tag,attrs); self.handle_endtag(tag)
    def handle_endtag(self,tag):
        for i in range(len(self.stack)-1,0,-1):
            if self.stack[i].tag==tag: self.stack=self.stack[:i]; break
    def handle_data(self,data): self.stack[-1].children.append(data)

def source(path):
    s=(ROOT/path).read_text()
    # Replace tiny PHP expressions without interpreting templates or running PHP.
    s=re.sub(r'<\?php echo NOAV_URI; \?>', '{{NOAV_ASSETS}}',s)
    s=re.sub(r"<\?php echo esc_url\( NOAV_URI \. '([^']*)' \); \?>",lambda m:'{{NOAV_ASSETS}}'+m[1],s)
    s=re.sub(r"<\?php echo esc_url\( home_url\( '([^']*)' \) \); \?>",lambda m:'{{NOAV_HOME}}'+m[1],s)
    s=re.sub(r'<\?php.*?\?>','',s,flags=re.S)
    return Tree(s).root

def block(name, attrs=None, content='', tag=None, classes=''):
    attrs=attrs or {}
    a=' '+json.dumps(attrs,ensure_ascii=False,separators=(',',':')) if attrs else ''
    if tag:
        content=f'<{tag}'+(f' class="{classes}"' if classes else '')+'>'+content+f'</{tag}>'
    return f'<!-- wp:{name}{a} -->\n{content}\n<!-- /wp:{name} -->'
def group(content, cls=''):
    return block('group',{'className':cls} if cls else {},content,'div','wp-block-group'+(' '+cls if cls else ''))
def columns(items, cls='noav-columns'):
    return block('columns',{'className':cls},'\n'.join(block('column',{},item,'div','wp-block-column') for item in items),'div','wp-block-columns '+cls)
def section(content,cls=''):
    return group(group(content,'noav-container'),'noav-section'+(' '+cls if cls else ''))
def inline(node):
    if isinstance(node,str): return escape(node,quote=False)
    content=''.join(inline(c) for c in node.children)
    if node.tag=='br': return '<br>'
    if node.tag in ('strong','em','b','i','sup','sub','s','u'):
        return f'<{node.tag}>{content}</{node.tag}>'
    if node.tag=='a':
        attrs=''.join(f' {k}="{escape(v,quote=True)}"' for k,v in node.attrs.items() if k in ('href','target','rel') and v)
        return f'<a{attrs}>{content}</a>'
    return content

def textblock(node):
    content=''.join(inline(c) for c in node.children).strip()
    if not node.text().replace('\xa0',' ').strip(): return ''
    center='text-align:center' in node.attrs.get('style','').replace(' ','')
    if re.match(r'^h[1-6]$',node.tag):
        attrs={'level':int(node.tag[1])}
        if center: attrs['textAlign']='center'
        cls='wp-block-heading'+(' has-text-align-center' if center else '')
        return block('heading',attrs,content,node.tag,cls)
    attrs={'align':'center'} if center else {}
    return block('paragraph',attrs,content,'p','has-text-align-center' if center else '')
def rich_nodes(root):
    return [n for n in root.walk() if n.tag in ('p','h1','h2','h3','h4','h5','h6','pre')]
def rich(root): return '\n'.join(filter(None,(textblock(n) for n in rich_nodes(root))))
def image(node, cls='', link=False, caption=None, title='Noav – bild'):
    src=node.attrs.get('src','')
    file=src.split('/')[-1]
    attrs={'id':f'{{{{NOAV_ID:{file}}}}}','sizeSlug':'large','linkDestination':'media' if link else 'none'}
    if cls: attrs['className']=cls
    alt=node.attrs.get('alt','').strip()
    if not alt or alt == 'background': alt=title
    metadata={'title': title if 'galleri bild' in title else alt, 'alt':alt}
    if file not in MEDIA or 'galleri bild' in title: MEDIA[file]=metadata
    img=f'<img src="{{{{NOAV_MEDIA:{file}}}}}" alt="{escape(alt,quote=True)}" class="wp-image-{{{{NOAV_ID:{file}}}}}"/>'
    if link: img=f'<a href="{{{{NOAV_MEDIA:{file}}}}}">{img}</a>'
    if caption: img+=f'<figcaption class="wp-element-caption">{escape(caption)}</figcaption>'
    result=block('image',attrs,img,'figure','wp-block-image size-large'+(' '+cls if cls else ''))
    # Numeric ID placeholders must be numbers in the final Gutenberg JSON.
    return re.sub(r'"(\{\{NOAV_ID:[^}]+\}\})"',r'\1',result)
def heading(text,level=1,center=False):
    n=Node('h'+str(level), [('style','text-align:center')] if center else []); n.children=[text]; return textblock(n)
def paragraph(text,center=False):
    n=Node('p',[('style','text-align:center')] if center else []); n.children=[text]; return textblock(n)
def button(link):
    content=f'<a class="wp-block-button__link wp-element-button" href="{escape(link.attrs.get("href",""),quote=True)}">{escape(link.text().strip())}</a>'
    return block('buttons',{},block('button',{},content,'div','wp-block-button'),'div','wp-block-buttons')
def standard(path,reverse=False):
    root=source(path)
    text=root.find(lambda n:'rich-text-block' in n.attrs.get('class','').split())
    img=root.find(lambda n:n.tag=='img')
    items=[group(rich(text),'noav-rich-content')]
    if img:
        unit='Söderbacken' if '/kyrkhult/' in path else 'Vinkelviken'
        label=next((n.text().strip() for n in rich_nodes(text) if n.tag.startswith('h')), 'Bild')
        items.append(image(img,'noav-section-image',title=unit+' – '+label))
    return section(columns(items,'noav-columns'+(' noav-columns-reverse' if reverse else '')) if img else items[0])
def home(unit):
    root=source(f'parts/{unit}/home.php')
    text=root.find(lambda n:'rich-text-block' in n.attrs.get('class','').split())
    content=rich(text)
    for link in root.all('a'):
        if 'button' in link.attrs.get('class','').split(): content+='\n'+button(link)
    img=root.find(lambda n:n.tag=='img')
    return section((image(img,'noav-hero-image',title=('Vinkelviken' if unit=='vinkelviken' else 'Söderbacken')+' – omslagsbild')+'\n' if img else '')+group(content,'noav-hero-content'),'noav-hero')
def gallery(unit):
    root=source(f'parts/{unit}/galleri.php')
    images=root.all('img')
    cols=3 if len(images)>1 else 1
    content='\n'.join(image(n,link=True,caption='Söderbacken, Kyrkhult' if unit=='kyrkhult' else None,title=('Vinkelviken' if unit=='vinkelviken' else 'Söderbacken')+' – galleri bild '+str(i)) for i,n in enumerate(images,1))
    attrs={'columns':cols,'linkTo':'media','className':'noav-gallery'}
    # core/gallery adds columns-N plus has-nested-images, with a cropped layout by default.
    gal=block('gallery',attrs,content,'figure',f'wp-block-gallery has-nested-images columns-{cols} is-cropped noav-gallery')
    return section(rich(root)+'\n'+gal)
def news():
    root=source('parts/vinkelviken/aktuellt.php')
    richroot=root.find(lambda n:'rich-text-block' in n.attrs.get('class','').split())
    groups=[]; current=[]
    for n in rich_nodes(richroot):
        if re.fullmatch(r'[_\s\xa0]+',n.text()):
            if current: groups.append(current); current=[]
        else: current.append(textblock(n))
    if current: groups.append(current)
    img=root.find(lambda n:n.tag=='img')
    content=heading('Aktuellt',1,True)
    if img: content+='\n'+image(img,'noav-news-image',title='Noav – Aktuellt')
    content+='\n'+'\n'.join(group('\n'.join(items),'noav-news-card') for items in groups)
    return section(content,'noav-news')
def contact():
    root=source('parts/global/kontakt.php')
    articles=root.all('article')
    return section(columns([rich(a) for a in articles],'noav-columns noav-contact-grid'),'noav-contact')
def landing():
    root=source('parts/landing.php')
    cards=[]
    for unit,a in zip(('vinkelviken','kyrkhult'),root.all('article')):
        content=[]
        for child in a.children:
            if not isinstance(child,Node): continue
            if child.tag in ('h2','p'): content.append(textblock(child))
            elif child.tag=='div' and child.text().strip()=='HVB': content.append(paragraph('HVB',True))
            elif child.tag=='a' and child.all('img'):
                img=child.all('img')[0]
                markup=image(img,'noav-unit-image')
                # Link image to the unit page, rather than its media file.
                markup=markup.replace('"linkDestination":"none"','"linkDestination":"custom"')
                markup=re.sub(r'(<img .*?/>)',lambda m:f'<a href="{{{{NOAV_HOME}}}}/{unit}/">'+m[1]+'</a>',markup)
                content.append(markup)
        content.append('<!-- wp:noav/availability '+json.dumps({'unit':unit},separators=(',',':'))+' /-->')
        cards.append(group('\n'.join(content),'noav-unit-card'))
    return section(columns(cards,'noav-columns noav-landing-grid'),'noav-landing')

pages={'hem':landing(),'oss':standard('parts/vinkelviken/oss.php'),'platsforfrogan':standard('parts/vinkelviken/platsforfrogan.php'),'kontakt':contact(),'aktuellt':news()}
for unit in ('vinkelviken','kyrkhult'):
    pages[unit]=home(unit)
    pages[unit+'/malgrupp']=standard(f'parts/{unit}/malgrupp.php',True)
    pages[unit+'/behandling']=standard(f'parts/{unit}/behandling.php')
    pages[unit+'/galleri']=gallery(unit)
(ROOT/'inc/seed-content.json').write_text(json.dumps({'version':1,'media':MEDIA,'pages':pages},ensure_ascii=False,indent=2)+'\n')
print('Seeded',len(pages),'native editable pages.')
for path,content in pages.items(): print(path,len(content))
